/**
 * Metadonnees et resume des sujets du Savoir.
 *
 * L'ARTICLE N'EST PAS ICI. Ce module est charge a l'ouverture de l'onglet, pour
 * afficher la grille des sujets ; il ne porte donc que ce qui est necessaire a
 * cet affichage. Les articles vivent dans `src/data/savoir/`, un module par
 * domaine, charges a la demande quand un sujet est ouvert.
 *
 * Ce fichier a longtemps porte un champ `content` d'environ 660 signes presente
 * a l'ecran comme « article complet ». Il a ete supprime : c'etait un second
 * resume, et le garder aurait fait telecharger 32 ko de texte mort a chaque
 * visite de l'onglet.
 *
 * `readTimeMinutes` est calcule a partir de l'article reel et verifie par
 * `scripts/verifie-savoir.mjs`. Ne pas le modifier a la main.
 */
export interface ExtendedKnowledgeItem {
  id: string;
  title: string;
  domainId: string;
  domainName: string;
  category: string;
  icon: string;
  color: string;
  readTimeMinutes: number;
  level: 'Débutant' | 'Intermédiaire' | 'Avancé';
  /** Resume court : sert a decider si on lit. */
  summary: string;
  keyConcepts: KnowledgeConcept[];
  relatedItemIds: string[];
  flashcards: KnowledgeFlashcard[];
}

